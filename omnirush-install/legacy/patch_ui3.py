edits = []
fail = []
extra = 0
for off, trans in T:
    e_ref = extract(ref, off)
    if e_ref < 0:
        fail.append((off, "无法提取字面量"))
        continue
    lit = ref[off:e_ref + 1]
    d = ref[off]
    # 模板字面量条目的译文自带首尾反引号时剥掉一层，避免 d + trans + d 变成双反引号
    if d == "`" and trans.startswith("`") and trans.endswith("`") and len(trans) >= 2:
        trans = trans[1:-1]
    if d in ("\"", "'") and d in trans:
        fail.append((off, "译文含定界符"))
        continue
    new_lit = d + trans + d
    # 同一文案可能在 bundle 里出现多次，全部替换（i18n 数据区除外）
    positions = []
    i = -1
    while True:
        i = ref.find(lit, i + 1)
        if i < 0:
            break
        if LANG_LO <= i < LANG_HI:
            continue
        positions.append(i)
    if not positions:
        fail.append((off, "快照中找不到字面量"))
        continue
    extra += len(positions) - 1
    for p in positions:
        e2 = extract(src, p)
        if e2 < 0 or src[p:e2 + 1] != lit:
            fail.append((p, "与快照不一致"))
            continue
        edits.append((p, e2 + 1, new_lit))

print(f"条目 {len(T)} 条 · 额外多出处 {extra} 处 · 待替换合计 {len(edits)} 处")

if fail:
    print(f"!! {len(fail)} 条未通过校验：")
    for off, why in fail[:40]:
        print(f"   @{off} {why}")
    sys.exit("已中止，未写入")

edits.sort(key=lambda x: x[0], reverse=True)
prev = None
for s, e, _ in edits:
    if prev is not None and e > prev:
        sys.exit(f"!! 区间重叠 @{s}")
    prev = s

out = src
for s, e, new in edits:
    out = out[:s] + new + out[e:]
print(f"共替换 {len(edits)} 处，长度 {orig_len} -> {len(out)} ({len(out)-orig_len:+d})")

