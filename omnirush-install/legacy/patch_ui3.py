def extract(s, i):
    """返回字面量结束定界符的下标；失败返回 -1"""
    d = s[i]
    j = i + 1
    if d == "`":
        depth = 0
        while j < len(s):
            c = s[j]
            if c == "\\":
                j += 2
                continue
            if c == "$" and j + 1 < len(s) and s[j + 1] == "{":
                depth += 1
                j += 2
                continue
            if c == "}" and depth > 0:
                depth -= 1
                j += 1
                continue
            if c == "`" and depth == 0:
                return j
            j += 1
        return -1
    while j < len(s):
        c = s[j]
        if c == "\\":
            j += 2
            continue
        if c == d:
            return j
        j += 1
    return -1


